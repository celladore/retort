/**
 * Retort — .retortconfig Generation Wizard (Phase 8)
 * Guides the user through generating a .retortconfig file for their project.
 *
 * Export: runRetortConfigWizard({ agentkitRoot, projectRoot, flags, prefill })
 *
 * Phases:
 *   A. Project block  — name, type, stacks, compliance
 *   B. Agent management (opt-in) — disable or remap agents from catalog
 *   C. Feature overrides (opt-in) — only deviations from defaults are written
 *   D. Write .retortconfig — yaml serialized, null rendered as ~
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'fs';
import yaml from 'js-yaml';
import { basename, resolve } from 'path';

// ---------------------------------------------------------------------------
// Constants
// ---------------------------------------------------------------------------

const COMPLIANCE_OPTIONS = [
  { value: 'gdpr', label: 'GDPR' },
  { value: 'hipaa', label: 'HIPAA' },
  { value: 'pci-dss', label: 'PCI-DSS' },
  { value: 'iso27001', label: 'ISO 27001' },
  { value: 'soc2', label: 'SOC 2' },
  { value: 'none', label: 'None' },
];

const CONFIG_HEADER = [
  '# =============================================================================',
  '# .retortconfig — Project configuration for the Retort framework',
  '# Generated by `retort init` — edit as needed.',
  '# Null values (~) indicate explicitly disabled agents.',
  '# =============================================================================',
  '',
].join('\n');

// ---------------------------------------------------------------------------
// Spec loaders
// ---------------------------------------------------------------------------

/**
 * Load all agent IDs from spec/agents/*.yaml files.
 * Returns Map<agentId, agentMeta>
 */
function loadAgentCatalog(agentkitRoot) {
  const agentsDir = resolve(agentkitRoot, 'spec', 'agents');
  const catalog = new Map();

  if (!existsSync(agentsDir)) return catalog;

  let files;
  try {
    files = readdirSync(agentsDir).filter((f) => f.endsWith('.yaml') || f.endsWith('.yml'));
  } catch {
    return catalog;
  }

  for (const file of files) {
    try {
      const raw = readFileSync(resolve(agentsDir, file), 'utf-8');
      const doc = yaml.load(raw);
      if (!doc || typeof doc !== 'object') continue;

      // Agent spec files use a top-level category key whose value is an array
      for (const [category, agents] of Object.entries(doc)) {
        if (!Array.isArray(agents)) continue;
        for (const agent of agents) {
          if (agent?.id) {
            catalog.set(agent.id, { category, ...agent });
          }
        }
      }
    } catch {
      // Skip malformed agent files
    }
  }

  return catalog;
}

/**
 * Load feature list from spec/features.yaml.
 * Returns array of { id, name, default, alwaysOn, category }
 */
function loadFeatureList(agentkitRoot) {
  const featuresPath = resolve(agentkitRoot, 'spec', 'features.yaml');
  if (!existsSync(featuresPath)) return [];

  try {
    const doc = yaml.load(readFileSync(featuresPath, 'utf-8'));
    return Array.isArray(doc?.features) ? doc.features : [];
  } catch {
    return [];
  }
}

// ---------------------------------------------------------------------------
// Auto-detect context for --config-only mode
// ---------------------------------------------------------------------------

function detectContextFromRepo(agentkitRoot, projectRoot) {
  const prefill = {};

  // Project name from .agentkit-repo marker
  const markerPath = resolve(projectRoot, '.agentkit-repo');
  if (existsSync(markerPath)) {
    try {
      prefill.projectName = readFileSync(markerPath, 'utf-8').trim() || basename(projectRoot);
    } catch {
      prefill.projectName = basename(projectRoot);
    }
  } else {
    prefill.projectName = basename(projectRoot);
  }

  // Stacks from spec/project.yaml
  const projectYamlPath = resolve(agentkitRoot, 'spec', 'project.yaml');
  if (existsSync(projectYamlPath)) {
    try {
      const doc = yaml.load(readFileSync(projectYamlPath, 'utf-8'));
      prefill.stacks = doc?.stack?.languages ?? [];
      prefill.enabledFeatures = doc?.features ? Object.keys(doc.features) : null;
    } catch {
      prefill.stacks = [];
    }
  } else {
    prefill.stacks = [];
  }

  return prefill;
}

// ---------------------------------------------------------------------------
// YAML serializer — null as ~
// ---------------------------------------------------------------------------

/**
 * Serialize config to YAML with null rendered as ~ (tilde) for disabled agents.
 * js-yaml renders null as '' by default in some schemas; we post-process to ~.
 */
function serializeConfig(config) {
  const raw = yaml.dump(config, {
    lineWidth: 120,
    noRefs: true,
    sortKeys: false,
    quotingType: '"',
    forceQuotes: false,
    // The DEFAULT_SCHEMA renders null as '', CORE_SCHEMA renders as 'null'.
    // We want '~' per YAML convention for disabled agents.
  });

  // Post-process: replace ': null\n' with ': ~\n' and ': null$' with ': ~'
  // Also handle list entries that are null: '- null' -> '- ~'
  return raw.replace(/: null(\n|$)/g, ': ~$1').replace(/^- null$/gm, '- ~');
}

// ---------------------------------------------------------------------------
// Non-interactive path
// ---------------------------------------------------------------------------

function buildNonInteractiveConfig(resolvedPrefill) {
  const stacks = Array.isArray(resolvedPrefill.stacks) ? resolvedPrefill.stacks : [];
  const config = {
    project: {
      name: resolvedPrefill.projectName || 'my-project',
      type: resolvedPrefill.type || 'application',
      ...(stacks.length > 0 ? { stacks } : { stacks: [] }),
    },
  };

  // Skip agents and features sections in non-interactive mode — let defaults apply
  return config;
}

// ---------------------------------------------------------------------------
// Main wizard
// ---------------------------------------------------------------------------

export async function runRetortConfigWizard({ agentkitRoot, projectRoot, flags = {}, prefill }) {
  const force = flags.force || false;
  const configPath = resolve(projectRoot, '.retortconfig');

  // Resolve prefill: use passed prefill, or auto-detect for --config-only mode
  const resolvedPrefill = prefill ?? detectContextFromRepo(agentkitRoot, projectRoot);

  // Load spec data
  const agentCatalog = loadAgentCatalog(agentkitRoot);
  const featureList = loadFeatureList(agentkitRoot);

  // Guard: don't overwrite without --force
  if (existsSync(configPath) && !force) {
    console.warn(
      `[retort] .retortconfig already exists at ${configPath}. Use --force to overwrite.`
    );
    return;
  }

  // Check if we can run interactively
  const isNonInteractive = flags['non-interactive'] || flags.ci || !process.stdout.isTTY;

  if (isNonInteractive) {
    const config = buildNonInteractiveConfig(resolvedPrefill);
    writeRetortConfigFile(configPath, config);
    console.log(`[retort] .retortconfig written to ${configPath}`);
    return;
  }

  // --- Interactive wizard ---
  let clack;
  try {
    if (typeof flags.__clackPrompts === 'function') {
      clack = await flags.__clackPrompts();
    } else if (typeof globalThis.__RETORT_TEST_CLACK_PROMPTS__ === 'function') {
      clack = await globalThis.__RETORT_TEST_CLACK_PROMPTS__();
    } else {
      const { resolveClackPrompts } = await import('./_clack-prompts.mjs');
      clack = await resolveClackPrompts();
    }
  } catch {
    console.warn(
      '[retort] @clack/prompts not available — falling back to non-interactive config generation.'
    );
    const config = buildNonInteractiveConfig(resolvedPrefill);
    writeRetortConfigFile(configPath, config);
    console.log(`[retort] .retortconfig written to ${configPath}`);
    return;
  }

  clack.intro('Retort — .retortconfig Wizard');

  // -------------------------------------------------------------------------
  // Phase A: Project block
  // -------------------------------------------------------------------------

  const projectName = await clack.text({
    message: 'Project name',
    initialValue: resolvedPrefill.projectName || basename(projectRoot),
    placeholder: 'my-project',
  });

  if (clack.isCancel(projectName)) {
    clack.cancel('Wizard cancelled.');
    return;
  }

  const projectType = await clack.text({
    message: 'Project type (e.g. application, library, service, cli)',
    initialValue: resolvedPrefill.type || 'application',
    placeholder: 'application',
  });

  if (clack.isCancel(projectType)) {
    clack.cancel('Wizard cancelled.');
    return;
  }

  // Stacks — multiselect from common choices; seeded from prefill
  const stackOptions = [
    { value: 'javascript', label: 'JavaScript' },
    { value: 'typescript', label: 'TypeScript' },
    { value: 'node', label: 'Node.js' },
    { value: 'python', label: 'Python' },
    { value: 'csharp', label: 'C# / .NET' },
    { value: 'rust', label: 'Rust' },
    { value: 'go', label: 'Go' },
    { value: 'java', label: 'Java / Kotlin' },
    { value: 'ruby', label: 'Ruby' },
  ];

  const prefillStacks = Array.isArray(resolvedPrefill.stacks) ? resolvedPrefill.stacks : [];
  const initialStacks = prefillStacks.filter((s) => stackOptions.some((opt) => opt.value === s));

  const selectedStacks = await clack.multiselect({
    message: 'Tech stacks (space to toggle)',
    options: stackOptions,
    initialValues: initialStacks,
    required: false,
  });

  if (clack.isCancel(selectedStacks)) {
    clack.cancel('Wizard cancelled.');
    return;
  }

  const complianceResult = await clack.multiselect({
    message: 'Compliance requirements (space to toggle, or select None)',
    options: COMPLIANCE_OPTIONS,
    initialValues: [],
    required: false,
  });

  if (clack.isCancel(complianceResult)) {
    clack.cancel('Wizard cancelled.');
    return;
  }

  const compliance = Array.isArray(complianceResult)
    ? complianceResult.filter((c) => c !== 'none')
    : [];

  // -------------------------------------------------------------------------
  // Phase B: Agent management (opt-in)
  // -------------------------------------------------------------------------

  const agents = {};

  if (agentCatalog.size > 0) {
    const configureAgents = await clack.confirm({
      message: 'Configure agent overrides? (disable or remap agents)',
      initialValue: false,
    });

    if (clack.isCancel(configureAgents)) {
      clack.cancel('Wizard cancelled.');
      return;
    }

    if (configureAgents) {
      const agentIds = [...agentCatalog.keys()];
      const agentOptions = agentIds.map((id) => {
        const meta = agentCatalog.get(id);
        return { value: id, label: `${id} (${meta.category})` };
      });

      const disabledAgents = await clack.multiselect({
        message: 'Select agents to disable (they will be set to null / ~)',
        options: agentOptions,
        initialValues: [],
        required: false,
      });

      if (clack.isCancel(disabledAgents)) {
        clack.cancel('Wizard cancelled.');
        return;
      }

      if (Array.isArray(disabledAgents)) {
        for (const id of disabledAgents) {
          agents[id] = null;
        }
      }

      // Remap step — agents not in the disabled set are candidates for remapping
      const remappable = agentIds.filter((id) => !Object.hasOwn(agents, id));
      // Only prompt remap if user wants to
      if (remappable.length > 0) {
        const wantRemap = await clack.confirm({
          message: 'Remap any agents to different teams/roles?',
          initialValue: false,
        });

        if (!clack.isCancel(wantRemap) && wantRemap) {
          const remapChoices = await clack.multiselect({
            message: 'Select agents to remap',
            options: remappable.map((id) => ({
              value: id,
              label: `${id} (${agentCatalog.get(id)?.category ?? 'unknown'})`,
            })),
            initialValues: [],
            required: false,
          });

          if (!clack.isCancel(remapChoices) && Array.isArray(remapChoices)) {
            for (const id of remapChoices) {
              const newTeam = await clack.text({
                message: `Remap "${id}" to team/role`,
                placeholder: 'e.g. backend, quality, devops',
              });
              if (!clack.isCancel(newTeam) && newTeam?.trim()) {
                agents[id] = { team: newTeam.trim() };
              }
            }
          }
        }
      }
    }
  }

  // -------------------------------------------------------------------------
  // Phase C: Feature overrides (opt-in, deviations from defaults only)
  // -------------------------------------------------------------------------

  const featureOverrides = {};

  const nonCoreFeatures = featureList.filter((f) => !f.alwaysOn);

  if (nonCoreFeatures.length > 0) {
    const configureFeatures = await clack.confirm({
      message: 'Override feature defaults?',
      initialValue: false,
    });

    if (clack.isCancel(configureFeatures)) {
      clack.cancel('Wizard cancelled.');
      return;
    }

    if (configureFeatures) {
      const featureOptions = nonCoreFeatures.map((f) => ({
        value: f.id,
        label: `${f.name || f.id} (${f.category})`,
        hint: f.default ? 'on by default' : 'off by default',
      }));

      const defaultEnabled = nonCoreFeatures.filter((f) => f.default).map((f) => f.id);

      // Pre-populate with passed enabledFeatures if present
      const initialEnabled = Array.isArray(resolvedPrefill?.enabledFeatures)
        ? resolvedPrefill.enabledFeatures.filter((id) => nonCoreFeatures.some((f) => f.id === id))
        : defaultEnabled;

      const selectedFeatures = await clack.multiselect({
        message: 'Select features to enable (deselect to disable; defaults shown pre-checked)',
        options: featureOptions,
        initialValues: initialEnabled,
        required: false,
      });

      if (clack.isCancel(selectedFeatures)) {
        clack.cancel('Wizard cancelled.');
        return;
      }

      // Only write deviations from defaults (no-op optimization)
      if (Array.isArray(selectedFeatures)) {
        for (const feature of nonCoreFeatures) {
          const isSelected = selectedFeatures.includes(feature.id);
          const isDefault = feature.default === true;

          if (isSelected !== isDefault) {
            // This is a deviation from the default — record it
            featureOverrides[feature.id] = isSelected;
          }
          // If isSelected === isDefault, omit it (no deviation)
        }
      }
    }
  }

  // -------------------------------------------------------------------------
  // Phase D: Write .retortconfig
  // -------------------------------------------------------------------------

  const config = {
    project: {
      name: typeof projectName === 'string' ? projectName.trim() : String(projectName),
      type: typeof projectType === 'string' ? projectType.trim() : String(projectType),
      stacks: Array.isArray(selectedStacks) ? selectedStacks : [],
      ...(compliance.length > 0 ? { compliance } : {}),
    },
  };

  if (Object.keys(agents).length > 0) {
    config.agents = agents;
  }

  if (Object.keys(featureOverrides).length > 0) {
    config.features = featureOverrides;
  }

  writeRetortConfigFile(configPath, config);

  clack.outro(`.retortconfig written — edit ${configPath} to adjust settings.`);
}

// ---------------------------------------------------------------------------
// File writer (also exported for programmatic use)
// ---------------------------------------------------------------------------

/**
 * Serialize `config` to YAML and write to `configPath`.
 * Null values are rendered as ~ (tilde) per YAML convention.
 */
export function writeRetortConfigFile(configPath, config) {
  const content = CONFIG_HEADER + serializeConfig(config);
  writeFileSync(configPath, content, 'utf-8');
}
